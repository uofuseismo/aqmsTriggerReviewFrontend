// waveformFilter.js
//
// A JavaScript port of the backend's waveform filtering, so a client can
// ask for unfiltered samples and do this itself.
//
// Why bother: the backend sends integer counts when it does not filter,
// and integers both serialise compactly and delta-encode well.  Filtering
// server-side turns them into fractional doubles that JSON writes as long
// scientific-notation strings.  Measured on a six-channel event, 73,649
// samples: server-filtered and quantized is 135 KB gzipped, while
// unfiltered with delta encoding is 92 KB - 32% smaller AND lossless,
// because nothing is quantized.  So filtering here is not only cheap, it
// makes the payload smaller.
//
// Request the samples with:  ?filter=false&enableDeltaEncoding=true
//
// The coefficients are a third-order Butterworth bandpass as second-order
// sections, generated by scipy in testing/data/signalProcessing/design.py
// and copied verbatim from src/signalProcessing/bandpass.cpp.  Verified
// against the same reference impulse responses the C++ is tested with:
// every sampling rate reproduces scipy sample-for-sample to 0.0.
//
// The passbands are 0.5 Hz to just under Nyquist, per design.py.

